#!/usr/bin/env python3
"""Development tool: writes win98/stubs.c.

The Win98 target leaves whole upstream modules out of the build (3D courses,
modern menus host, mods, Lua, store, course editor, split-screen, touch,
file chooser, other-game importers). Upstream's shared game shell still
references their entry points, so each one gets an inert definition with the
exact upstream prototype: "feature absent" (0 / NULL / no-op).

Usage: gen_stubs.py LINK_LOG   (a link log listing the undefined references)
Re-run after changing the excluded file list in CMakeLists.txt.
"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent
portable = here.parent / "portable"

# Stubs whose "absent" answer is not simply zero.
SPECIAL = {
    # "No request pending" for the optional file chooser: 2 = cancelled.
    "portable_file_dialog_poll": "(void)request; (void)path; (void)capacity; return 2;",
    # The shell requires a 3D-course host object to exist; this one is an
    # opaque token that every other stub reports as empty and inactive.
    "portable_course_3d_host_create": "static char absent[16]; return (void *)absent;",
    "portable_course_3d_host_wait_idle": "return 1;",
    # No touch overlay to draw: success, or every present would fail.
    "portable_mobile_touch_draw": "return 1;",
    # Same contract as upstream with no script host: clear the hooks, succeed.
    "portable_script_host_begin_race": "if (session == NULL) return 0; session->script_hooks = NULL; return 1;",
    "portable_script_host_begin_time_trial": "if (session == NULL) return 0; session->script_hooks = NULL; return 1;",
    # An empty mod root list is valid.
    "portable_mod_roots_valid": "(void)roots; return 1;",
}

def undefined(log_text):
    return sorted(set(re.findall(r"undefined reference to [`'](\w+)'", log_text)))

def prototypes():
    found = {}
    for header in sorted(portable.glob("**/*.h")):
        if "third_party" in header.parts or "android" in header.parts:
            continue
        text = header.read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        text = re.sub(r"//[^\n]*", " ", text)
        text = re.sub(r"^\s*#.*$", " ", text, flags=re.M)
        for statement in text.split(";"):
            if "{" in statement or "}" in statement or "typedef" in statement:
                continue
            statement = " ".join(statement.split())
            match = re.match(r"^(.*?)\b(\w+)\s*\((.*)\)$", statement)
            if match and match.group(1).strip() and "(" not in match.group(1):
                found.setdefault(match.group(2), (header, statement, match.group(1).strip()))
    return found

def main():
    names = undefined(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace"))
    known = prototypes()
    headers, bodies, missing = [], [], []
    for name in names:
        if name not in known:
            missing.append(name)
            continue
        header, statement, returns = known[name]
        include = header.relative_to(portable).as_posix()
        if include not in headers:
            headers.append(include)
        returns = returns.replace("extern ", "")
        if name in SPECIAL:
            body = SPECIAL[name]
        elif returns == "void":
            body = ""
        else:
            body = f"return ({returns}){{0}};"
        bodies.append(f"{statement}\n{{ {body} }}".replace("{  }", "{}"))
    out = ["/* GENERATED by gen_stubs.py - inert definitions for upstream modules that are",
           " * not part of the Windows 98 build. See gen_stubs.py for the rules. */",
           "#define PORTABLE_ENABLE_SDL3 1", "#include <SDL3/SDL.h>"]
    out += [f'#include "../portable/{include}"' for include in headers]
    out += ["", "#pragma GCC diagnostic ignored \"-Wunused-parameter\"", ""]
    out += bodies
    (here / "stubs.c").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"stubs.c: {len(bodies)} stubs from {len(headers)} headers")
    if missing:
        print("NO PROTOTYPE FOUND:", " ".join(missing))

main()
